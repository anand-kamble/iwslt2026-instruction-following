"""Spoken Question Answering dataset loading and preprocessing.

Permitted dataset: LibriSQA (ZihanZhao/LibriSQA on HuggingFace)
Audio: references LibriSpeech files (download train-clean-360 separately)
Multilingual: translated JSONL files generated by src/data/translate_sqa.py
"""

import json

from datasets import load_dataset

from src.data.utils import TASK_PROMPTS, UNANSWERABLE, format_chat_messages, get_data_dir


def load_sqa_dataset(split: str = "train", language: str = "en"):
    """Load the LibriSQA dataset for spoken question answering.

    For English: loads from HuggingFace (ZihanZhao/LibriSQA).
    For other languages: loads from translated JSONL files (same audio, translated text).

    Note: Audio is NOT embedded. The 'speech_path' field references LibriSpeech files.
    Download LibriSpeech train-clean-360 to data/LibriSpeech/.
    """
    if language != "en":
        return load_translated_sqa_dataset(split, language)

    # Map split names: our "train" -> LibriSQA "partI.train"
    split_map = {"train": "partI.train", "test": "partI.test"}
    hf_split = split_map.get(split, split)

    ds = load_dataset(
        "ZihanZhao/LibriSQA",
        data_files={"partI.train": "LibriSQA-PartI/LibriSQA-PartI-train.json",
                     "partI.test": "LibriSQA-PartI/LibriSQA-PartI-test.json"},
        split=hf_split,
    )

    librispeech_root = get_data_dir()

    def _format(example):
        question = example.get("question", "")
        answer = example.get("answer", "")

        prompt_template = TASK_PROMPTS["sqa"][language]
        instruction = prompt_template.replace("{QUESTION}", question)

        # Mark unanswerable
        if not answer or answer.lower().strip() in ("unanswerable", "not answerable"):
            answer = UNANSWERABLE[language]

        example["messages"] = format_chat_messages(instruction, answer)

        # Resolve audio path relative to data dir
        speech_path = example.get("speech_path", "")
        if speech_path:
            example["audio_path"] = str(librispeech_root / speech_path)

        return example

    return ds.map(_format)


def load_translated_sqa_dataset(split: str = "train", language: str = "de"):
    """Load synthetic translated SQA dataset from local JSONL files.

    Uses same audio as LibriSQA but with translated question/answer text.
    Generated by src/data/translate_sqa.py with COMETKiwi filtering.
    """
    jsonl_path = get_data_dir() / "sqa_translated" / f"librisqa_{language}.jsonl"
    if not jsonl_path.exists():
        raise FileNotFoundError(
            f"Translated SQA data not found at {jsonl_path}. "
            f"Run: python -m src.data.translate_sqa --languages {language}"
        )

    # Load translations
    translations = {}
    with open(jsonl_path) as f:
        for line in f:
            record = json.loads(line)
            translations[record["id"]] = record

    # Load original LibriSQA for audio paths
    original_ds = load_dataset("ZihanZhao/LibriSQA", split="partI.train")
    librispeech_root = get_data_dir()

    def _format(example, idx):
        if idx in translations:
            t = translations[idx]
            question = t["question"]
            answer = t["answer"]
        else:
            # Filtered out by COMETKiwi — use English fallback
            question = example.get("question", "")
            answer = example.get("answer", "")

        prompt_template = TASK_PROMPTS["sqa"][language]
        instruction = prompt_template.replace("{QUESTION}", question)

        if not answer or answer.lower().strip() in ("unanswerable", "not answerable"):
            answer = UNANSWERABLE[language]

        example["messages"] = format_chat_messages(instruction, answer)

        # Resolve audio path
        speech_path = example.get("speech_path", "")
        if speech_path:
            example["audio_path"] = str(librispeech_root / speech_path)

        return example

    return original_ds.map(_format, with_indices=True)
